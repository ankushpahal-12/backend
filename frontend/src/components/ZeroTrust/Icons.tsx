/**
 * Get device icon component based on user agent
 */
// eslint-disable-next-line react-refresh/only-export-components
export const getDeviceIcon = (userAgent: string, className = "w-5 h-5") => {
    if (userAgent.includes('Windows')) {
        return <WindowsIcon className={className} />;
    } else if (userAgent.includes('Mac')) {
        return <MacIcon className={className} />;
    } else if (userAgent.includes('Android')) {
        return <AndroidIcon className={className} />;
    } else if (userAgent.includes('iPhone') || userAgent.includes('iOS')) {
        return <IPhoneIcon className={className} />;
    }
    return <ComputerIcon className={className} />;
};
